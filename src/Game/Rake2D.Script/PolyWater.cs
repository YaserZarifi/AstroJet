using System;
using System.Collections.Generic;
using Microsoft.Xna.Framework;

namespace Rake2D.Script;

public class PolyWater : BehaviorScript
{
	private List<PolygonVertex> _vertexList;

	private List<PolygonVertex> _originalVertexList;

	private List<Vector2> _topVertexList;

	private List<Vector2> _originalTopVertexList;

	private float _angle;

	private float _amplitude;

	private float _speed;

	private float _phase;

	private float _flowSpeed;

	private int _segmentWidth;

	private bool _isInitialized;

	private bool _isLastVertexIsSameAsFirst;

	public override void RegisterEvents()
	{
		MyObject.OnUpdate += OnUpdate;
	}

	public override void Init()
	{
		base.Init();
		MyObject.PolygonRenderer.IsAutogenerated = true;
		_amplitude = Param("amp");
		_speed = Param("speed") / 1000f;
		_phase = Utils.DegToRad(Param("phase"));
		_segmentWidth = Math.Max(10, ParamInt("segment_width", 64));
		_flowSpeed = Param("flow_speed", 30f);
		_isLastVertexIsSameAsFirst = ParamBool("sync_end");
	}

	public void BuildStrip()
	{
		float num = MyObject.PolygonRenderer.BoundingBottomRight.X - MyObject.PolygonRenderer.BoundingTopLeft.X;
		int num2 = ((MyObject.PolygonRenderer.Data.Atlas == null) ? MyObject.PolygonRenderer.Data.Texture.Height : MyObject.PolygonRenderer.Data.Atlas.GetFrameRectangle(MyObject.PolygonRenderer.Data.AtlasFrame).Height);
		_vertexList = GameCore.Allocator.GetPolygonVertexList();
		float num3 = 0f;
		while (num3 <= num)
		{
			_vertexList.AddVertex(new Vector2(num3 - num / 2f, num2 / 2));
			_vertexList.AddVertex(new Vector2(num3 - num / 2f, -num2 / 2));
			num3 += (float)_segmentWidth / MyObject.Scale.X;
			if (num3 > num || _vertexList.Count > 100)
			{
				_vertexList.AddVertex(new Vector2(num / 2f, num2 / 2));
				_vertexList.AddVertex(new Vector2(num / 2f, -num2 / 2));
				break;
			}
		}
		MyObject.PolygonRenderer.SetVertices(_vertexList);
		MyObject.CreateRigidBodyByPoygonRenderer();
		_originalVertexList = GameCore.Allocator.GetPolygonVertexList();
		int count = _vertexList.Count;
		for (int i = 0; i < count; i++)
		{
			_originalVertexList.Add(GameCore.Allocator.ClonePolygonVertex(_vertexList[i]));
		}
		_topVertexList = MyObject.PolygonRenderer.TopVertexList;
		_originalTopVertexList = GameCore.Allocator.GetVector2List();
		count = _topVertexList.Count;
		for (int j = 0; j < count; j++)
		{
			_originalTopVertexList.Add(_topVertexList[j]);
		}
	}

	private void OnUpdate(float elapsedTime)
	{
		if (!_isInitialized)
		{
			BuildStrip();
			_isInitialized = true;
		}
		_angle = MyLevel.Timer * _speed;
		for (int i = 1; i < _vertexList.Count; i += 2)
		{
			float num = (float)Math.Sin(_angle + (float)i * _phase);
			Vector2 vector = new Vector2(0f, num * _amplitude);
			_vertexList[i].Position = _originalVertexList[i].Position + vector;
		}
		MyObject.PolygonRenderer.TextureFlowOffset += new Vector2(_flowSpeed * 1.5f / (float)MyObject.PolygonRenderer.Data.TopTexture.Width * elapsedTime, 0f);
		if (!MyObject.PolygonRenderer.TopSurfaceInfoArray.IsNullOrEmpty())
		{
			MyObject.PolygonRenderer.TopSurfaceInfoArray[0].FlowOffset += _flowSpeed / (float)MyObject.PolygonRenderer.Data.TopTexture.Width * elapsedTime;
		}
		for (int j = 0; j < _topVertexList.Count; j += 2)
		{
			float num2 = (float)Math.Sin(_angle + (float)j * (_phase + (float)Math.PI / 2f));
			Vector2 vector2 = new Vector2(0f, (-1f + num2 / 2f) * _amplitude * 1.25f);
			_topVertexList[j] = _originalTopVertexList[j] + vector2;
		}
		for (int k = 1; k < _topVertexList.Count; k += 2)
		{
			float num3 = (float)Math.Sin(_angle + (float)k * (_phase + (float)Math.PI / 4f));
			Vector2 vector3 = new Vector2(0f, (1f + num3 / 2f) * _amplitude * 0.5f);
			_topVertexList[k] = _originalTopVertexList[k] + vector3;
		}
		if (_isLastVertexIsSameAsFirst)
		{
			_vertexList[_vertexList.Count - 1].Position.Y = _vertexList[1].Position.Y;
			_topVertexList[_topVertexList.Count - 1] = new Vector2(_topVertexList[_topVertexList.Count - 1].X, _topVertexList[1].Y);
			_topVertexList[_topVertexList.Count - 2] = new Vector2(_topVertexList[_topVertexList.Count - 2].X, _topVertexList[0].Y);
		}
	}
}
