using System;
using System.Collections.Generic;
using Microsoft.Xna.Framework;

namespace Rake2D.Script;

public class PolyFlag : BehaviorScript
{
	private List<PolygonVertex> _vertexList;

	private List<PolygonVertex> _originalVertexList;

	private float _sideAngle;

	private float _pendlumAngle;

	private float _zAngle;

	private float _chaosAngle;

	private float _pendulumAmplitude;

	private float _pendulumSpeed;

	private float _sideAmplitude;

	private float _sideSpeed;

	private float _sidePhase;

	private float _zAmplitude;

	private float _zSpeed;

	private float _chaosAmplitude;

	private float _chaosSpeed;

	private float _chaosPhase;

	private int _fixedSegmentCount;

	private bool _isInitialized;

	public override void RegisterEvents()
	{
		MyObject.OnUpdate += OnUpdate;
		if (_doInEditor && GameCore.IsEditorEnabled)
		{
			MyObject.OnEditorUpdate += OnUpdate;
		}
	}

	public override void Init()
	{
		base.Init();
		MyObject.PolygonRenderer.IsAutogenerated = true;
		_pendulumSpeed = Param("pendulum_speed") / 360f;
		_pendulumAmplitude = Param("pendulum_amp");
		_zAmplitude = Param("z_amp");
		_zSpeed = Param("z_speed", 360f) / 360f;
		_sideAmplitude = Param("side_amp");
		_sideSpeed = Param("side_speed") / 360f;
		_sidePhase = Param("side_phase");
		_chaosAmplitude = Param("chaos_amp");
		_chaosSpeed = Param("chaos_speed") / 360f;
		_chaosPhase = Param("chaos_phase");
		_fixedSegmentCount = ParamInt("fixed_segment");
		_sideAngle = Utils.GetRandom(0f, (float)Math.PI * 2f);
		_pendlumAngle = Utils.GetRandom(0f, (float)Math.PI * 2f);
		_zAngle = Utils.GetRandom(0f, (float)Math.PI * 2f);
		_chaosAngle = Utils.GetRandom(0f, (float)Math.PI * 2f);
	}

	private float GetSegmentPercent(int vertexNumber)
	{
		return (float)Math.Max(0, vertexNumber / 2 - (_fixedSegmentCount - 1)) / Math.Max(1f, (float)(_vertexList.Count - 2) / 2f - (float)_fixedSegmentCount);
	}

	public void BuildStrip(int segmentCount)
	{
		if (MyObject.PolygonRenderer == null)
		{
			return;
		}
		int width;
		int height;
		if (MyObject.PolygonRenderer.Data.Atlas != null)
		{
			Rectangle frameRectangle = MyObject.PolygonRenderer.Data.Atlas.GetFrameRectangle(MyObject.PolygonRenderer.Data.AtlasFrame);
			width = frameRectangle.Width;
			height = frameRectangle.Height;
		}
		else
		{
			width = MyObject.PolygonRenderer.Data.Texture.Width;
			height = MyObject.PolygonRenderer.Data.Texture.Height;
		}
		if (MyObject.PolygonRenderer.Data.Texture == null)
		{
			return;
		}
		_vertexList = GameCore.Allocator.GetPolygonVertexList();
		Vector2 pivotOffset = MyObject.PartData.PolygonData.PivotOffset;
		switch (MyObject.PolygonRenderer.Data.Orientation)
		{
		case PolygonOritentation.LeftRight:
		{
			_vertexList.AddVertex(new Vector2((float)(-width / 2) - pivotOffset.X, (float)(height / 2) - pivotOffset.Y));
			_vertexList.AddVertex(new Vector2((float)(-width / 2) - pivotOffset.X, (float)(-height / 2) - pivotOffset.Y));
			float num2 = (float)width / (float)segmentCount;
			for (int j = 0; j < segmentCount; j++)
			{
				_vertexList.AddVertex(new Vector2(_vertexList[j * 2].Position.X + num2, (float)(height / 2) - pivotOffset.Y));
				_vertexList.AddVertex(new Vector2(_vertexList[j * 2 + 1].Position.X + num2, (float)(-height / 2) - pivotOffset.Y));
			}
			break;
		}
		case PolygonOritentation.BottomTop:
		{
			_vertexList.AddVertex(new Vector2((float)(width / 2) - pivotOffset.X, (float)(height / 2) - pivotOffset.Y));
			_vertexList.AddVertex(new Vector2((float)(-width / 2) - pivotOffset.X, (float)(height / 2) - pivotOffset.Y));
			float num = (float)height / (float)segmentCount;
			for (int k = 0; k < segmentCount; k++)
			{
				_vertexList.AddVertex(new Vector2((float)(width / 2) - pivotOffset.X, _vertexList[k * 2].Position.Y - num));
				_vertexList.AddVertex(new Vector2((float)(-width / 2) - pivotOffset.X, _vertexList[k * 2 + 1].Position.Y - num));
			}
			break;
		}
		default:
		{
			_vertexList.AddVertex(new Vector2((float)(-width / 2) - pivotOffset.X, (float)(-height / 2) - pivotOffset.Y));
			_vertexList.AddVertex(new Vector2((float)(width / 2) - pivotOffset.X, (float)(-height / 2) - pivotOffset.Y));
			float num = (float)height / (float)segmentCount;
			for (int i = 0; i < segmentCount; i++)
			{
				_vertexList.AddVertex(new Vector2((float)(-width / 2) - pivotOffset.X, _vertexList[i * 2].Position.Y + num));
				_vertexList.AddVertex(new Vector2((float)(width / 2) - pivotOffset.X, _vertexList[i * 2 + 1].Position.Y + num));
			}
			break;
		}
		}
		MyObject.PolygonRenderer.SetVertices(_vertexList);
		MyObject.CreateRigidBodyByPoygonRenderer();
		_originalVertexList = GameCore.Allocator.GetPolygonVertexList();
		_ = _vertexList.Count;
		for (int l = 0; l < _vertexList.Count; l++)
		{
			_originalVertexList.Add(GameCore.Allocator.ClonePolygonVertex(_vertexList[l]));
		}
	}

	private void OnUpdate(float elapsedTime)
	{
		if (!_isInitialized)
		{
			BuildStrip(ParamInt("segment_count", 4));
			_isInitialized = true;
		}
		float rotation;
		if (_pendulumSpeed != 0f)
		{
			_pendlumAngle += elapsedTime * _pendulumSpeed;
			rotation = (float)Math.Sin(_pendlumAngle);
		}
		else
		{
			rotation = 0f;
		}
		float num;
		if (_zSpeed != 0f)
		{
			_zAngle += elapsedTime * _zSpeed;
			num = (float)Math.Sin(_zAngle);
		}
		else
		{
			num = 0f;
		}
		_sideAngle += elapsedTime * _sideSpeed;
		_chaosAngle += elapsedTime * _chaosSpeed;
		PolygonOritentation orientation = MyObject.PolygonRenderer.Data.Orientation;
		Matrix matrix = ((orientation != PolygonOritentation.LeftRight) ? Matrix.Identity : Matrix.CreateRotationZ(-(float)Math.PI / 2f));
		for (int i = _fixedSegmentCount * 2; i < _vertexList.Count; i += 2)
		{
			float segmentPercent = GetSegmentPercent(i - _fixedSegmentCount);
			float num2 = (float)Math.Sin(_sideAngle + segmentPercent * _sidePhase);
			float num3 = (float)Math.Sin(_chaosAngle + segmentPercent * _chaosPhase);
			Vector2 position = new Vector2(num * (0f - _zAmplitude) * segmentPercent, num * _zAmplitude * segmentPercent);
			position += new Vector2(num2 * segmentPercent * _sideAmplitude, 0f);
			position += new Vector2(Utils.Sin(rotation), Utils.Cos(rotation)) * segmentPercent * _pendulumAmplitude;
			position += new Vector2(num3 * segmentPercent * _chaosAmplitude, num3 * segmentPercent * _chaosAmplitude);
			position = Vector2.Transform(position, matrix);
			_vertexList[i].Position = _originalVertexList[i].Position + position;
			num3 = (float)Math.Sin(_chaosAngle + segmentPercent * _chaosPhase * 0.9f);
			position = new Vector2(num * _zAmplitude * segmentPercent, num * _zAmplitude * segmentPercent);
			position += new Vector2(num2 * segmentPercent * _sideAmplitude, 0f);
			position += new Vector2(Utils.Sin(rotation), Utils.Cos(rotation)) * segmentPercent * _pendulumAmplitude;
			position += new Vector2(num3 * segmentPercent * _chaosAmplitude, num3 * segmentPercent * _chaosAmplitude);
			position = Vector2.Transform(position, matrix);
			_vertexList[i + 1].Position = _originalVertexList[i + 1].Position + position;
		}
	}
}
