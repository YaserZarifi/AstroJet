using System;
using System.Collections.Generic;
using Microsoft.Xna.Framework;
using Microsoft.Xna.Framework.Graphics;

namespace Rake2D;

public class PolygonRenderer
{
	public PolygonData Data;

	public Vector2 BoundingTopLeft;

	public Vector2 BoundingBottomRight;

	public Vector2 TextureOffset;

	public bool IsTopEnabled;

	public bool IsBottomEnabled;

	public bool IsAutogenerated;

	public PolygonTextureMappingModeEnum TextureMappingMode;

	public GameObject MyObject;

	public Vector2 TextureFlowOffset;

	public PolygonSurfaceInfo[] TopSurfaceInfoArray;

	private Color _color;

	private float _surfaceTextureX;

	private float _topSurfaceHeight;

	private Vector2 _frameUVTopLeft;

	private Vector2 _frameUVBottomRight;

	public List<PolygonVertex> VertexList { get; private set; }

	public List<Vector2> TopVertexList { get; private set; }

	public List<Vector2> BottomVertexList { get; private set; }

	public bool IsTopEdgeOnly
	{
		get
		{
			if (TopVertexList != null && BottomVertexList == null)
			{
				return Data.Texture == null;
			}
			return false;
		}
	}

	public void Init(PolygonData data, GameObject go)
	{
		VertexList = GameCore.Allocator.GetPolygonVertexList();
		Data = data;
		MyObject = go;
		TextureMappingMode = Data.TextureMappingMode;
		if (TextureMappingMode == PolygonTextureMappingModeEnum.RelativeToPivot && Data.Texture != null)
		{
			TextureOffset = new Vector2(-0.5f, -0.5f);
		}
		IsTopEnabled = (IsBottomEnabled = true);
		if (Data.Atlas != null)
		{
			Data.Atlas.GetFrameUV(data.AtlasFrame, out _frameUVTopLeft, out _frameUVBottomRight);
		}
		else
		{
			_frameUVTopLeft = Vector2.Zero;
			_frameUVBottomRight = Vector2.One;
		}
		if (Data.TopAtlas != null && data.TopAtlasFrameArray != null)
		{
			TopSurfaceInfoArray = new PolygonSurfaceInfo[data.TopAtlasFrameArray.Length];
			for (int i = 0; i < data.TopAtlasFrameArray.Length; i++)
			{
				Data.TopAtlas.GetFrameUV(data.TopAtlasFrameArray[i], out var topLeft, out var bottomRight);
				TopSurfaceInfoArray[i].FrameUVTop = topLeft.Y;
				TopSurfaceInfoArray[i].FrameUVBottom = bottomRight.Y;
			}
			_topSurfaceHeight = Data.TopAtlas.GetFrameRectangle(data.TopAtlasFrameArray[0]).Height;
		}
		else
		{
			TopSurfaceInfoArray = new PolygonSurfaceInfo[1];
			TopSurfaceInfoArray[0].FrameUVTop = 0f;
			TopSurfaceInfoArray[0].FrameUVBottom = 1f;
			if (Data.TopTexture != null)
			{
				_topSurfaceHeight = Data.TopTexture.Height;
			}
		}
	}

	public PolygonRenderer Copy(GameObject go)
	{
		if (go.PolygonRenderer == null)
		{
			return null;
		}
		PolygonRenderer polygonRenderer = GameCore.Allocator.GetPolygonRenderer(go.PolygonRenderer.Data ?? Data, go);
		polygonRenderer.BoundingTopLeft = BoundingTopLeft;
		polygonRenderer.BoundingBottomRight = BoundingBottomRight;
		polygonRenderer.IsTopEnabled = IsTopEnabled;
		polygonRenderer.IsBottomEnabled = IsBottomEnabled;
		polygonRenderer.IsAutogenerated = IsAutogenerated;
		polygonRenderer.TextureMappingMode = TextureMappingMode;
		polygonRenderer.TextureOffset = TextureOffset;
		polygonRenderer.VertexList = GameCore.Allocator.DeleteOwningPolygonVertexList(polygonRenderer.VertexList);
		polygonRenderer.TopVertexList = GameCore.Allocator.DeleteVector2List(polygonRenderer.TopVertexList);
		polygonRenderer.BottomVertexList = GameCore.Allocator.DeleteVector2List(polygonRenderer.BottomVertexList);
		if (VertexList != null)
		{
			polygonRenderer.VertexList = GameCore.Allocator.GetPolygonVertexList();
			int count = VertexList.Count;
			for (int i = 0; i < count; i++)
			{
				polygonRenderer.VertexList.Add(GameCore.Allocator.ClonePolygonVertex(VertexList[i]));
			}
		}
		if (TopVertexList != null)
		{
			polygonRenderer.TopVertexList = GameCore.Allocator.GetVector2List();
			polygonRenderer.TopVertexList.AddList(TopVertexList);
		}
		if (BottomVertexList != null)
		{
			polygonRenderer.BottomVertexList = GameCore.Allocator.GetVector2List();
			polygonRenderer.BottomVertexList.AddList(BottomVertexList);
		}
		return polygonRenderer;
	}

	public void ClearPolygonRenderer()
	{
		Data = null;
		VertexList = GameCore.Allocator.DeleteOwningPolygonVertexList(VertexList);
		TopVertexList = GameCore.Allocator.DeleteVector2List(TopVertexList);
		BottomVertexList = GameCore.Allocator.DeleteVector2List(BottomVertexList);
		BoundingTopLeft = Vector2.Zero;
		BoundingBottomRight = Vector2.Zero;
		TextureOffset = Vector2.Zero;
		IsTopEnabled = false;
		IsBottomEnabled = false;
		IsAutogenerated = false;
		TextureMappingMode = PolygonTextureMappingModeEnum.RelativeToLevel;
		MyObject = null;
		TextureFlowOffset = Vector2.Zero;
		TopSurfaceInfoArray = null;
		_ = Color.White;
		_surfaceTextureX = 0f;
		_topSurfaceHeight = 0f;
		_frameUVTopLeft = Vector2.Zero;
		_frameUVBottomRight = Vector2.Zero;
	}

	public void SetVertices(float[] vertextArray)
	{
		GameCore.Allocator.DeleteOwningPolygonVertexList(VertexList);
		VertexList = GameCore.Allocator.GetPolygonVertexList();
		for (int i = 0; i < vertextArray.Length; i += 2)
		{
			AddVertex(new Vector2(vertextArray[i], vertextArray[i + 1]));
		}
		RecalculateData();
	}

	public void SetVertices(List<PolygonVertex> vertexList)
	{
		GameCore.Allocator.DeleteOwningPolygonVertexList(VertexList);
		VertexList = vertexList;
		RecalculateData();
	}

	public void AddVertex(Vector2 position, int index = -1)
	{
		AddVertex(GameCore.Allocator.GetPolygonVertex(position), index);
	}

	public void AddVertex(PolygonVertex position, int index = -1)
	{
		if (index < 0 || index >= VertexList.Count)
		{
			VertexList.Add(position);
		}
		else
		{
			VertexList.Insert(index, position);
		}
	}

	private void BuildTopSurface()
	{
		GameCore.Allocator.DeleteVector2List(TopVertexList);
		TopVertexList = GameCore.Allocator.GetVector2List();
		if (VertexList.Count < 3)
		{
			return;
		}
		for (int i = 1; i < VertexList.Count; i += 2)
		{
			Vector2 zero = Vector2.Zero;
			if (i == 1)
			{
				zero = VertexList[0].Position - VertexList[i].Position;
				if (zero != Vector2.Zero)
				{
					zero.Normalize();
				}
				zero = new Vector2(zero.Y, 0f - zero.X);
			}
			else if (i >= VertexList.Count - 2)
			{
				zero = VertexList[i - 1].Position - VertexList[i].Position;
				if (zero != Vector2.Zero)
				{
					zero.Normalize();
				}
				zero = new Vector2(zero.Y, 0f - zero.X);
			}
			else
			{
				Vector2 vector = VertexList[i + 2].Position - VertexList[i].Position;
				if (vector != Vector2.Zero)
				{
					vector.Normalize();
				}
				Vector2 vector2 = VertexList[i - 2].Position - VertexList[i].Position;
				if (vector2 != Vector2.Zero)
				{
					vector2.Normalize();
				}
				zero = vector - vector2;
				if (zero != Vector2.Zero)
				{
					zero.Normalize();
				}
			}
			TopVertexList.Add(VertexList[i].Position - new Vector2(zero.Y, 0f - zero.X) * -Data.TopOffset);
			TopVertexList.Add(VertexList[i].Position + new Vector2(0f - zero.Y, zero.X) * ((float)(-Data.TopOffset) + _topSurfaceHeight));
		}
	}

	private void BuildBottomSurface()
	{
		GameCore.Allocator.DeleteVector2List(BottomVertexList);
		BottomVertexList = GameCore.Allocator.GetVector2List();
		if (VertexList.Count < 3)
		{
			return;
		}
		for (int i = 0; i < VertexList.Count; i += 2)
		{
			Vector2 zero = Vector2.Zero;
			if (i == 0)
			{
				zero = VertexList[1].Position - VertexList[i].Position;
				if (zero != Vector2.Zero)
				{
					zero.Normalize();
				}
				zero = new Vector2(0f - zero.Y, zero.X);
			}
			else if (i >= VertexList.Count - 3)
			{
				zero = VertexList[i + 1].Position - VertexList[i].Position;
				if (zero != Vector2.Zero)
				{
					zero.Normalize();
				}
				zero = new Vector2(0f - zero.Y, zero.X);
			}
			else
			{
				Vector2 vector = VertexList[i + 2].Position - VertexList[i].Position;
				if (vector != Vector2.Zero)
				{
					vector.Normalize();
				}
				Vector2 vector2 = VertexList[i - 2].Position - VertexList[i].Position;
				if (vector2 != Vector2.Zero)
				{
					vector2.Normalize();
				}
				zero = vector - vector2;
				if (zero != Vector2.Zero)
				{
					zero.Normalize();
				}
			}
			BottomVertexList.Add(VertexList[i].Position + new Vector2(0f - zero.Y, zero.X) * Data.BottomOffset);
			BottomVertexList.Add(VertexList[i].Position - new Vector2(zero.Y, 0f - zero.X) * (Data.BottomOffset - Data.BottomTexture.Height));
		}
	}

	public void RemoveVertex(int index)
	{
		if (index >= 0 || index < VertexList.Count)
		{
			GameCore.Allocator.DeletePolygonVertex(VertexList[index]);
			VertexList.RemoveAt(index);
		}
	}

	public void RecalculateData()
	{
		if (Data.TopTexture != null && IsTopEnabled)
		{
			BuildTopSurface();
		}
		else
		{
			TopVertexList = GameCore.Allocator.DeleteVector2List(TopVertexList);
		}
		if (Data.BottomTexture != null && IsBottomEnabled)
		{
			BuildBottomSurface();
		}
		else
		{
			BottomVertexList = GameCore.Allocator.DeleteVector2List(BottomVertexList);
		}
		UpdateBoundingBox();
	}

	public void SetColor(int r, int g, int b, int a)
	{
		_color = new Color(r, g, b, a);
	}

	private void UpdateBoundingBox()
	{
		BoundingTopLeft = Vector2.Zero;
		BoundingBottomRight = Vector2.Zero;
		int count = VertexList.Count;
		for (int i = 0; i < count; i++)
		{
			PolygonVertex polygonVertex = VertexList[i];
			BoundingTopLeft.X = Math.Min(BoundingTopLeft.X, polygonVertex.Position.X);
			BoundingTopLeft.Y = Math.Min(BoundingTopLeft.Y, polygonVertex.Position.Y);
			BoundingBottomRight.X = Math.Max(BoundingBottomRight.X, polygonVertex.Position.X);
			BoundingBottomRight.Y = Math.Max(BoundingBottomRight.Y, polygonVertex.Position.Y);
		}
	}

	public Vector2[] GetBoundingBoxVerices(Transformation worldTransformation, bool bWorld)
	{
		Vector2[] rectangleVertices = GameCore.Allocator.GetRectangleVertices();
		Matrix matrix = Matrix.CreateScale(worldTransformation.Scale.X, worldTransformation.Scale.Y, 1f) * Matrix.CreateRotationZ(worldTransformation.Rotation);
		if (bWorld)
		{
			matrix *= Matrix.CreateTranslation(worldTransformation.Position.X, worldTransformation.Position.Y, 1f);
		}
		rectangleVertices[0] = Vector2.Transform(BoundingTopLeft, matrix);
		rectangleVertices[1] = Vector2.Transform(new Vector2(BoundingBottomRight.X, BoundingTopLeft.Y), matrix);
		rectangleVertices[2] = Vector2.Transform(BoundingBottomRight, matrix);
		rectangleVertices[3] = Vector2.Transform(new Vector2(BoundingTopLeft.X, BoundingBottomRight.Y), matrix);
		return rectangleVertices;
	}

	private void DrawSurface(TriangleBatchTextured triangleBatch)
	{
		if (Data.BottomTexture != null && IsBottomEnabled)
		{
			BatchVertextTextured[] drawSurfaceVertices = GetDrawSurfaceVertices(BottomVertexList, Data.BottomTexture, 1, 0f, 0f, 1f);
			if (drawSurfaceVertices != null)
			{
				triangleBatch.DrawStrip(drawSurfaceVertices, BottomVertexList.Count, Data.BottomTexture);
			}
			GameCore.Allocator.DeleteBatchVertextTextured(drawSurfaceVertices);
		}
		if (Data.TopTexture == null || !IsTopEnabled)
		{
			return;
		}
		for (int i = 0; i < TopSurfaceInfoArray.Length; i++)
		{
			PolygonSurfaceInfo polygonSurfaceInfo = TopSurfaceInfoArray[i];
			BatchVertextTextured[] drawSurfaceVertices = GetDrawSurfaceVertices(TopVertexList, Data.TopTexture, 0, polygonSurfaceInfo.FlowOffset, polygonSurfaceInfo.FrameUVTop, polygonSurfaceInfo.FrameUVBottom);
			if (drawSurfaceVertices != null)
			{
				triangleBatch.DrawStrip(drawSurfaceVertices, TopVertexList.Count, Data.TopTexture);
			}
			GameCore.Allocator.DeleteBatchVertextTextured(drawSurfaceVertices);
		}
	}

	private BatchVertextTextured[] GetDrawSurfaceVertices(List<Vector2> vertextList, Texture2D texture, int evenOddOffset, float flowOffset, float uvTop, float uvBottom)
	{
		if (vertextList != null && vertextList.Count > 2)
		{
			BatchVertextTextured[] batchVertextTextured = GameCore.Allocator.GetBatchVertextTextured(vertextList.Count);
			for (int i = 0; i <= vertextList.Count - 1; i++)
			{
				batchVertextTextured[i] = default;
				batchVertextTextured[i].Position = Vector2.Transform(vertextList[i], MyObject.WorldMatrix);
				batchVertextTextured[i].Color = _color;
				PolygonTextureMappingModeEnum textureMappingMode = TextureMappingMode;
				if (textureMappingMode == PolygonTextureMappingModeEnum.FixedHeight)
				{
					batchVertextTextured[i].TextureCoordinate.X = batchVertextTextured[i].Position.X / (float)Data.Texture.Width;
					if ((i + evenOddOffset) % 2 == 0)
					{
						batchVertextTextured[i].TextureCoordinate.Y = uvTop;
					}
					else
					{
						batchVertextTextured[i].TextureCoordinate.Y = uvBottom;
					}
				}
				else
				{
					if (i == 0 || i == 1)
					{
						_surfaceTextureX = 0f;
					}
					else if (i % 2 == 0)
					{
						_surfaceTextureX += (batchVertextTextured[i].Position - batchVertextTextured[i - 2].Position).Length() / (float)texture.Width;
					}
					batchVertextTextured[i].TextureCoordinate.X = _surfaceTextureX;
					if ((i + evenOddOffset) % 2 == 0)
					{
						batchVertextTextured[i].TextureCoordinate.Y = uvTop;
					}
					else
					{
						batchVertextTextured[i].TextureCoordinate.Y = uvBottom;
					}
				}
				batchVertextTextured[i].TextureCoordinate.X += flowOffset;
			}
			return batchVertextTextured;
		}
		return null;
	}

	public void MoveAllVertices(Vector2 offset)
	{
		if (VertexList != null)
		{
			for (int i = 0; i < VertexList.Count; i++)
			{
				VertexList[i].ChangePosition(offset);
			}
		}
	}

	public void Draw(TriangleBatchTextured triangleBatch)
	{
		if (Data.Texture != null && VertexList.Count > 2)
		{
			BatchVertextTextured[] batchVertextTextured = GameCore.Allocator.GetBatchVertextTextured(VertexList.Count);
			for (int num = VertexList.Count - 1; num >= 0; num--)
			{
				batchVertextTextured[num] = default;
				batchVertextTextured[num].Position = Vector2.Transform(VertexList[num].Position, MyObject.WorldMatrix);
				switch (TextureMappingMode)
				{
				case PolygonTextureMappingModeEnum.RelativeToPivot:
					batchVertextTextured[num].TextureCoordinate.X = VertexList[num].Position.X / (float)Data.Texture.Width;
					batchVertextTextured[num].TextureCoordinate.Y = VertexList[num].Position.Y / (float)Data.Texture.Height;
					break;
				case PolygonTextureMappingModeEnum.FixedHeight:
					batchVertextTextured[num].TextureCoordinate.X = batchVertextTextured[num].Position.X / (float)Data.Texture.Width;
					batchVertextTextured[num].TextureCoordinate.Y = ((num % 2 == 0) ? _frameUVBottomRight.X : _frameUVTopLeft.X);
					break;
				case PolygonTextureMappingModeEnum.FixedRect:
					switch (Data.Orientation)
					{
					case PolygonOritentation.TopBottom:
						batchVertextTextured[num].TextureCoordinate.X = ((num % 2 != 0) ? _frameUVBottomRight.X : _frameUVTopLeft.X);
						batchVertextTextured[num].TextureCoordinate.Y = _frameUVTopLeft.Y + (_frameUVBottomRight.Y - _frameUVTopLeft.Y) * (float)(num / 2) / ((float)(VertexList.Count - 2) / 2f);
						break;
					case PolygonOritentation.BottomTop:
						batchVertextTextured[num].TextureCoordinate.X = ((num % 2 == 0) ? _frameUVBottomRight.X : _frameUVTopLeft.X);
						batchVertextTextured[num].TextureCoordinate.Y = _frameUVBottomRight.Y - (_frameUVBottomRight.Y - _frameUVTopLeft.Y) * (float)(num / 2) / ((float)(VertexList.Count - 2) / 2f);
						break;
					default:
						batchVertextTextured[num].TextureCoordinate.X = _frameUVTopLeft.X + (_frameUVBottomRight.X - _frameUVTopLeft.X) * (float)(num / 2) / ((float)(VertexList.Count - 2) / 2f);
						batchVertextTextured[num].TextureCoordinate.Y = ((num % 2 == 0) ? _frameUVBottomRight.Y : _frameUVTopLeft.Y);
						break;
					}
					break;
				default:
					batchVertextTextured[num].TextureCoordinate.X = batchVertextTextured[num].Position.X / (float)Data.Texture.Width;
					batchVertextTextured[num].TextureCoordinate.Y = batchVertextTextured[num].Position.Y / (float)Data.Texture.Height;
					break;
				}
				batchVertextTextured[num].Color = Color.FromNonPremultiplied(_color.R, _color.G, _color.B, (int)((float)(int)_color.A / 255f * (float)(int)VertexList[num].Color.A));
				batchVertextTextured[num].TextureCoordinate += TextureOffset + TextureFlowOffset;
			}
			triangleBatch.DrawStrip(batchVertextTextured, VertexList.Count, Data.Texture);
			GameCore.Allocator.DeleteBatchVertextTextured(batchVertextTextured);
		}
		DrawSurface(triangleBatch);
	}
}
